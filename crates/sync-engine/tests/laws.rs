//! Algebraic laws for the merge engine (§16, implementation-plan 0.5).
//!
//! Because `merge` is pure (§11.3), we can assert real algebraic laws over
//! generated characters. These catch the interleaving bugs that example-based
//! tests structurally cannot.
//!
//! ## Laws asserted (§16, §21 risk row)
//!
//! 1. **Merge identity** — merging a build with itself is a no-op preview.
//! 2. **`merge(a, x, x)` never conflicts** — both sides changed identically.
//! 3. **Single-sided changes never lost** — a change on exactly one side
//!    appears in `auto_merged`.
//! 4. **`hash(x) == hash(roundtrip(x))`** — serialization is deterministic and
//!    lossless (§9.2).
//! 5. **Identical inputs never produce conflicts** (§21 risk row).
//! 6. **Conflicts are symmetric** — swapping `ours`/`theirs` yields the same
//!    conflict set with `ours`/`theirs` swapped (the UI is order-agnostic).
//!
//! ## Strategies
//!
//! Builds are generated by perturbing `minimal_build()` along a small set of
//! axes (name, level, feat slugs, skill keys). This is deliberately not a
//! full schema generator — the point is to exercise the merge/diff logic
//! across meaningful divergence combinations, not to fuzz the schema itself
//! (which is covered by `schema-core`'s invariant tests).

use proptest::prelude::*;
use schema_core::ability::{
    AbilityBoost, AbilityBoostSource, AbilityScoreEntry, AbilityScoreKey, SkillEntry,
};
use schema_core::build_types::*;
use schema_core::character::CharacterBuild;
use schema_core::content_hash;
use schema_core::newtypes::{Level, SkillKey};
use schema_core::proficiency::ProficiencyRank;
use schema_core::refs::SystemRefId;
use schema_core::testing::minimal_build;

use sync_engine::diff::diff;
use sync_engine::merge::merge;

// ── Enum strategies (these enums don't impl Arbitrary; provide them) ───────

fn proficiency_rank_strategy() -> impl Strategy<Value = ProficiencyRank> {
    prop_oneof![
        Just(ProficiencyRank::Untrained),
        Just(ProficiencyRank::Trained),
        Just(ProficiencyRank::Expert),
        Just(ProficiencyRank::Master),
        Just(ProficiencyRank::Legendary),
    ]
}

fn ability_key_strategy() -> impl Strategy<Value = AbilityScoreKey> {
    prop_oneof![
        Just(AbilityScoreKey::Str),
        Just(AbilityScoreKey::Dex),
        Just(AbilityScoreKey::Con),
        Just(AbilityScoreKey::Int),
        Just(AbilityScoreKey::Wis),
        Just(AbilityScoreKey::Cha),
    ]
}

// ── Strategies ─────────────────────────────────────────────────────────────

fn level_strategy() -> impl Strategy<Value = Level> {
    (1u8..=20).prop_map(|n| Level::new(n).expect("1..=20 is valid"))
}

fn name_strategy() -> impl Strategy<Value = String> {
    "[a-zA-Z0-9 ]{1,20}"
}

/// A small set of feat slugs to draw from — enough to exercise identity-matched
/// pairing (inserts, removes, reorders) without a full content index.
fn feat_slug_strategy() -> impl Strategy<Value = String> {
    prop_oneof![
        Just("power-attack".to_string()),
        Just("toughness".to_string()),
        Just("combat-reflexes".to_string()),
        Just("cleave".to_string()),
        Just("dodge".to_string()),
    ]
}

fn feats_strategy() -> impl Strategy<Value = Vec<FeatEntry>> {
    // Unique slugs only — duplicate identities make the identity-matched path
    // ambiguous (two items resolve to the same `build.feats[slug]` path), which
    // is a schema-level concern, not a merge-engine concern. Generate a
    // permutation of 0..=5 of the 5 available slugs.
    prop::collection::vec(feat_slug_strategy(), 0..5).prop_map(|slugs| {
        let mut seen = std::collections::HashSet::new();
        slugs
            .into_iter()
            .filter(|s| seen.insert(s.clone()))
            .map(|slug| FeatEntry {
                reference: SystemRefId::from_slug(slug),
                category: FeatCategory::General,
                level: Level::new(1).unwrap(),
            })
            .collect()
    })
}

fn skill_key_strategy() -> impl Strategy<Value = SkillKey> {
    prop_oneof![
        Just(SkillKey::new("athletics")),
        Just(SkillKey::new("diplomacy")),
        Just(SkillKey::new("stealth")),
        Just(SkillKey::new("arcana")),
        Just(SkillKey::new("lore:alchemy")),
    ]
}

fn skill_entry_strategy() -> impl Strategy<Value = (SkillKey, SkillEntry)> {
    (skill_key_strategy(), proficiency_rank_strategy()).prop_map(|(k, rank)| {
        (
            k,
            SkillEntry {
                rank,
                lore: None,
                item_bonus: 0,
            },
        )
    })
}

fn skills_strategy() -> impl Strategy<Value = std::collections::BTreeMap<SkillKey, SkillEntry>> {
    prop::collection::vec(skill_entry_strategy(), 0..4)
        .prop_map(|pairs| pairs.into_iter().collect())
}

fn ability_scores_strategy(
) -> impl Strategy<Value = std::collections::BTreeMap<AbilityScoreKey, AbilityScoreEntry>> {
    // Pick 0..3 abilities to populate with a single free boost each.
    prop::collection::vec(
        ability_key_strategy().prop_map(|k| {
            (
                k,
                AbilityScoreEntry {
                    boosts: vec![AbilityBoost {
                        source: AbilityBoostSource::Free,
                    }],
                    flaws: vec![],
                    item_bonus: 0,
                },
            )
        }),
        0..3,
    )
    .prop_map(|pairs| pairs.into_iter().collect())
}

/// A `CharacterBuild` strategy built by perturbing `minimal_build()`. Keeps
/// the fixture's structural validity (right number of fields, valid refs)
/// while varying the fields the merge engine actually diff/merges on.
fn build_strategy() -> impl Strategy<Value = CharacterBuild> {
    (
        name_strategy(),
        level_strategy(),
        feats_strategy(),
        skills_strategy(),
        ability_scores_strategy(),
    )
        .prop_map(|(name, level, feats, skills, ability_scores)| {
            let mut b = minimal_build();
            b.identity.name = name;
            b.level = level;
            b.feats = feats;
            b.skills = skills;
            b.ability_scores = ability_scores;
            b
        })
}

// ── Law 1: merge identity ──────────────────────────────────────────────────

proptest! {
    #![proptest_config(ProptestConfig {
        cases: 256,
        ..ProptestConfig::default()
    })]

    #[test]
    fn law_merge_identity(a in build_strategy()) {
        // §16: merging a build with itself is identity.
        let m = merge(&a, &a, &a);
        prop_assert!(
            m.auto_merged.is_empty(),
            "identity merge must have no auto-merged fields: {:?}",
            m.auto_merged
        );
        prop_assert!(
            m.conflicts.is_empty(),
            "identity merge must have no conflicts: {:?}",
            m.conflicts
        );
    }

    // ── Law 2: merge(a, x, x) never conflicts ──────────────────────────────

    #[test]
    fn law_merge_a_xx_never_conflicts(a in build_strategy(), x in build_strategy()) {
        // §16 / §21: both sides changed identically → no conflicts.
        let m = merge(&a, &x, &x);
        prop_assert!(
            m.conflicts.is_empty(),
            "merge(a, x, x) must never conflict: {:?}",
            m.conflicts
        );
    }

    // ── Law 3: single-sided changes never lost ─────────────────────────────

    #[test]
    fn law_single_sided_change_preserved(a in build_strategy(), x in build_strategy()) {
        // §16: a change made on exactly one side appears in auto_merged.
        // ours = x, theirs = a (theirs unchanged).
        let m = merge(&a, &x, &a);
        let expected = diff(&a, &x);
        // Every path changed on our side must show up in auto_merged.
        let auto_paths: std::collections::HashSet<_> =
            m.auto_merged.iter().map(|d| d.path.as_str()).collect();
        for d in &expected {
            prop_assert!(
                auto_paths.contains(d.path.as_str()),
                "single-sided change at {} was lost (not in auto_merged): {:?}",
                d.path.as_str(),
                m
            );
        }
        prop_assert!(
            m.conflicts.is_empty(),
            "single-sided change must not conflict: {:?}",
            m.conflicts
        );
    }

    // ── Law 4: hash(x) == hash(roundtrip(x)) ───────────────────────────────

    #[test]
    fn law_hash_roundtrip(x in build_strategy()) {
        // §9.2, §16: serialization is deterministic and lossless.
        let json = serde_json::to_string(&x).expect("serializable");
        let back: CharacterBuild = serde_json::from_str(&json).expect("deserializable");
        let h1 = content_hash(&x);
        let h2 = content_hash(&back);
        prop_assert_eq!(h1, h2, "hash must be stable across a serde round-trip");
        prop_assert_eq!(&x, &back, "round-trip must be lossless");
    }

    // ── Law 5: identical inputs never produce conflicts (§21 risk row) ─────

    #[test]
    fn law_identical_inputs_no_conflicts(
        a in build_strategy(),
        b in build_strategy(),
    ) {
        // Any merge where ours == theirs cannot conflict (both sides made the
        // same change relative to ancestor, whatever the ancestor is).
        let m = merge(&a, &b, &b);
        prop_assert!(
            m.conflicts.is_empty(),
            "identical ours==theirs must never conflict: {:?}",
            m.conflicts
        );
    }

    // ── Law 6: conflicts are symmetric under ours/theirs swap ──────────────

    #[test]
    fn law_conflicts_symmetric(
        a in build_strategy(),
        ours in build_strategy(),
        theirs in build_strategy(),
    ) {
        let m1 = merge(&a, &ours, &theirs);
        let m2 = merge(&a, &theirs, &ours);

        // Same number of conflicts.
        prop_assert_eq!(m1.conflicts.len(), m2.conflicts.len());

        // Each conflict in m1 has a counterpart in m2 with ours/theirs swapped.
        for c1 in &m1.conflicts {
            let counterpart = m2.conflicts.iter().find(|c2| c2.path == c1.path);
            prop_assert!(
                counterpart.is_some(),
                "conflict at {} missing in swapped merge",
                c1.path
            );
            let c2 = counterpart.unwrap();
            prop_assert_eq!(&c1.ancestor, &c2.ancestor, "ancestor mismatch at {}", c1.path);
            prop_assert_eq!(&c1.ours, &c2.theirs, "ours/theirs swap mismatch at {}", c1.path);
            prop_assert_eq!(&c1.theirs, &c2.ours, "ours/theirs swap mismatch at {}", c1.path);
        }
    }

    // ── Law 7 (bonus): diff(a, a) is always empty ──────────────────────────

    #[test]
    fn law_diff_self_is_empty(a in build_strategy()) {
        let d = diff(&a, &a);
        prop_assert!(d.is_empty(), "diff(a, a) must be empty: {:?}", d);
    }

    // ── Law 8 (bonus): diff is anti-symmetric ──────────────────────────────

    #[test]
    fn law_diff_antisymmetric(a in build_strategy(), b in build_strategy()) {
        // diff(a, b) and diff(b, a) touch the same paths; each Modified in
        // one direction inverts before/after in the other.
        let d_ab = diff(&a, &b);
        let d_ba = diff(&b, &a);
        let paths_ab: std::collections::HashSet<_> =
            d_ab.iter().map(|d| d.path.as_str()).collect();
        let paths_ba: std::collections::HashSet<_> =
            d_ba.iter().map(|d| d.path.as_str()).collect();
        prop_assert_eq!(paths_ab, paths_ba, "diff paths must match under swap");
    }
}
