//! Codegen pipeline — Rust types → canonical.schema.json → TS types + Zod (§3.6).
//!
//! The one-way pipeline:
//!
//! ```text
//! crates/schema-core (Rust types)    ← the only hand-written definition
//!         │ schemars::schema_for!
//!         ▼
//!   canonical.schema.json            ← published artifact, committed
//!         │
//!         ├─► json2ts                ─► @nexus-sheet/schema-types  (TS types)
//!         └─► json-schema-to-zod     ─► @nexus-sheet/schema-zod   (runtime validation)
//! ```
//!
//! Run via `cargo xtask codegen`. The generated output is **committed to the
//! repo**, and CI regenerates and fails on any diff (`cargo xtask codegen && git
//! diff --exit-code`). Committing generated code earns its place here: a TS
//! contributor can clone, `pnpm install`, and have working types without a Rust
//! toolchain anywhere in their loop (§0.1).
//!
//! Generation runs toward the less-expressive target (§3.6): Rust → JSON Schema
//! → TS, never the reverse, because Rust needs newtypes with construction-time
//! invariants, `BTreeMap` ordering, and exhaustive enums that JSON Schema
//! can't express.

use std::fs;
use std::io::Write;
use std::process::{Command, ExitCode, Stdio};

use schema_core::Character;
/// The canonical JSON Schema artifact (§3.6). Committed; published for
/// third-party tooling in any language.
const SCHEMA_PATH: &str = "canonical.schema.json";

/// Generated TS types (§3.6).
const TYPES_PATH: &str = "packages/schema-types/src/index.ts";

/// Generated Zod validators (§3.6).
const ZOD_PATH: &str = "packages/schema-zod/src/index.ts";

/// Banner prepended to every generated file so hand-edits are obvious in review
/// and in `git blame`.
const HEADER: &str = "// GENERATED — do not hand-edit (§3.6, §15).\n\
// Source of truth: crates/schema-core/src/*.rs\n\
// Regenerated by `cargo xtask codegen`; CI fails on staleness.\n\
\n";

/// Run the full codegen pipeline.
pub fn run() -> ExitCode {
    if !generate_schema() {
        return ExitCode::FAILURE;
    }
    if !generate_types() {
        return ExitCode::FAILURE;
    }
    if !generate_zod() {
        return ExitCode::FAILURE;
    }
    eprintln!("codegen: done — {SCHEMA_PATH}, {TYPES_PATH}, {ZOD_PATH}");
    ExitCode::SUCCESS
}

// ── Step 1: Rust types → canonical.schema.json ─────────────────────────────

fn generate_schema() -> bool {
    eprintln!("codegen: generating {SCHEMA_PATH} from schema-core::Character");
    let schema = schemars::schema_for!(Character);
    let mut value = match serde_json::to_value(&schema) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("codegen: FAILED to serialize schema: {e}");
            return false;
        }
    };
    // `schemars` 0.8 wraps referenced types as `{ "allOf": [{ "$ref": "..." }],
    // "description": "..." }`. `json2ts` handles this fine, but
    // `json-schema-to-zod` doesn't resolve `$ref` inside `allOf`. Normalise to
    // a bare `{ "$ref": "..." }` — the description lives on the definition
    // itself, so nothing is lost. This is a standard JSON Schema simplification.
    normalize_refs(&mut value);
    let json = match serde_json::to_string_pretty(&value) {
        Ok(j) => j,
        Err(e) => {
            eprintln!("codegen: FAILED to serialize schema: {e}");
            return false;
        }
    };
    if let Err(e) = fs::write(SCHEMA_PATH, json + "\n") {
        eprintln!("codegen: FAILED to write {SCHEMA_PATH}: {e}");
        return false;
    }
    true
}

// ── $ref normalisation ─────────────────────────────────────────────────────
//
// `schemars` 0.8 emits `{ "allOf": [{ "$ref": "#/definitions/Foo" }],
// "description": "..." }` for referenced types. This is valid JSON Schema, but
// `json-schema-to-zod` doesn't resolve `$ref` inside `allOf`. We unwrap any
// `allOf` containing exactly one `$ref` into a bare `$ref`, preserving
// sibling `description` (which some tools read even in draft-07).

fn normalize_refs(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(obj) => {
            // Check if this object has `allOf` with exactly one `$ref` entry.
            if let Some(all_of) = obj.get("allOf").and_then(|v| v.as_array()) {
                if all_of.len() == 1
                    && all_of[0]
                        .as_object()
                        .is_some_and(|o| o.contains_key("$ref"))
                {
                    let ref_val = all_of[0]["$ref"].clone();
                    let description = obj.get("description").cloned();
                    obj.clear();
                    obj.insert("$ref".to_string(), ref_val);
                    if let Some(desc) = description {
                        obj.insert("description".to_string(), desc);
                    }
                    return;
                }
            }
            // Recurse into all object values.
            for (_, v) in obj.iter_mut() {
                normalize_refs(v);
            }
        }
        serde_json::Value::Array(arr) => {
            for v in arr.iter_mut() {
                normalize_refs(v);
            }
        }
        _ => {}
    }
}

// ── Step 2: canonical.schema.json → @nexus-sheet/schema-types ──────────────

fn generate_types() -> bool {
    eprintln!("codegen: generating {TYPES_PATH} via json2ts");
    let status = Command::new("pnpm")
        .args([
            "exec",
            "json2ts",
            SCHEMA_PATH,
            "--output",
            TYPES_PATH,
            // Skip prettier — we don't want a prettier dependency in the
            // codegen path, and generated code doesn't need to be pretty.
            "--no-style",
            // Don't emit the eslint-disable banner; we prepend our own header.
            "--no-header-comment",
        ])
        .status();
    match status {
        Ok(s) if s.success() => {
            if !prepend_header(TYPES_PATH) {
                return false;
            }
            true
        }
        Ok(s) => {
            eprintln!("codegen: json2ts exited with {s}");
            false
        }
        Err(e) => {
            eprintln!("codegen: FAILED to run json2ts: {e}");
            false
        }
    }
}

// ── Step 3: canonical.schema.json → @nexus-sheet/schema-zod ────────────────
//
// `json-schema-to-zod` doesn't resolve internal `$ref`s — its README
// recommends piping through `json-refs` first. We inline `$ref`s in Rust
// instead, avoiding another Node dependency. The canonical schema keeps its
// `$ref`s (it's the published artifact, §3.6); inlining is only for the zod
// tool's consumption.

fn generate_zod() -> bool {
    eprintln!("codegen: generating {ZOD_PATH} via json-schema-to-zod");

    let schema_json = match fs::read_to_string(SCHEMA_PATH) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("codegen: FAILED to read {SCHEMA_PATH}: {e}");
            return false;
        }
    };
    let mut schema: serde_json::Value = match serde_json::from_str(&schema_json) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("codegen: FAILED to parse {SCHEMA_PATH}: {e}");
            return false;
        }
    };
    inline_refs(&mut schema);
    let inlined_json = match serde_json::to_string(&schema) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("codegen: FAILED to serialize inlined schema: {e}");
            return false;
        }
    };

    let mut child = match Command::new("pnpm")
        .args([
            "exec",
            "json-schema-to-zod",
            "--module",
            "esm",
            "--name",
            "characterSchema",
            "--output",
            ZOD_PATH,
        ])
        .stdin(Stdio::piped())
        .spawn()
    {
        Ok(c) => c,
        Err(e) => {
            eprintln!("codegen: FAILED to spawn json-schema-to-zod: {e}");
            return false;
        }
    };
    if let Some(stdin) = child.stdin.as_mut() {
        if let Err(e) = stdin.write_all(inlined_json.as_bytes()) {
            eprintln!("codegen: FAILED to write to json-schema-to-zod stdin: {e}");
            return false;
        }
    }
    match child.wait() {
        Ok(s) if s.success() => prepend_header(ZOD_PATH),
        Ok(s) => {
            eprintln!("codegen: json-schema-to-zod exited with {s}");
            false
        }
        Err(e) => {
            eprintln!("codegen: FAILED to wait for json-schema-to-zod: {e}");
            false
        }
    }
}

// ── $ref inlining (for json-schema-to-zod only) ────────────────────────────

const MAX_INLINE_DEPTH: usize = 100;

fn inline_refs(schema: &mut serde_json::Value) {
    let definitions = schema
        .get("definitions")
        .and_then(|d| d.as_object())
        .cloned()
        .unwrap_or_default();
    inline_refs_recursive(schema, &definitions, 0);
    if let Some(obj) = schema.as_object_mut() {
        obj.remove("definitions");
    }
}

fn inline_refs_recursive(
    value: &mut serde_json::Value,
    definitions: &serde_json::Map<String, serde_json::Value>,
    depth: usize,
) {
    if depth >= MAX_INLINE_DEPTH {
        return;
    }

    // Check if this value is an object with a $ref to #/definitions/...
    let replacement = value.as_object().and_then(|obj| {
        let ref_str = obj.get("$ref")?.as_str()?;
        let def_name = ref_str.strip_prefix("#/definitions/")?;
        let def = definitions.get(def_name)?.clone();
        let mut inlined = def;
        // Preserve sibling properties (e.g. description) — don't overwrite
        // keys already present in the definition.
        if let Some(inlined_obj) = inlined.as_object_mut() {
            for (key, val) in obj {
                if key != "$ref" {
                    inlined_obj.entry(key.clone()).or_insert(val.clone());
                }
            }
        }
        Some(inlined)
    });

    if let Some(replacement) = replacement {
        *value = replacement;
        inline_refs_recursive(value, definitions, depth + 1);
        return;
    }

    match value {
        serde_json::Value::Object(obj) => {
            for (_, v) in obj.iter_mut() {
                inline_refs_recursive(v, definitions, depth);
            }
        }
        serde_json::Value::Array(arr) => {
            for v in arr.iter_mut() {
                inline_refs_recursive(v, definitions, depth);
            }
        }
        _ => {}
    }
}

// ── Header prepending ──────────────────────────────────────────────────────

fn prepend_header(path: &str) -> bool {
    let existing = match fs::read_to_string(path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("codegen: FAILED to read {path} for header: {e}");
            return false;
        }
    };
    let combined = format!("{HEADER}{existing}");
    if let Err(e) = fs::write(path, combined) {
        eprintln!("codegen: FAILED to write header to {path}: {e}");
        return false;
    }
    true
}
